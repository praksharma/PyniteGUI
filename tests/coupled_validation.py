"""Reproducible solved flat-surface fixtures and bounded validation evidence.

Closed-form references live in coupled_reference and import no solver/app code.
No prescribed displacements, artificial rigid links or stiffness changes are
used. Raw-engine drilling diagnostics are never accepted application snapshots.
"""
import contextlib
import io

import numpy as np
from Pynite import FEModel3D

from coupled_reference import membrane_displacement, membrane_stress, strip_solution
from pynitegui.qt.analysis import AnalysisResult, analyze, model_signature
from pynitegui.qt.equilibrium import check_equilibrium
from pynitegui.qt.mesh_model import MeshDefinition
from pynitegui.qt.model import Material, Section
from pynitegui.qt.spatial_model import SpatialProject, SpatialMember, SpatialLoad, RESTRAINT_FIELDS, DOFS
from pynitegui.qt.spatial_surfaces import surface_geometry
from pynitegui.qt.surface_results import centre_results
from pynitegui.qt.surface_solver import attach_surfaces


# Deliberately independent of the app's axis map: non-square YZ tests must
# catch an accidental swap of width/height instead of copying the same error.
AXES = {"XY": (0, 1, 2), "XZ": (0, 2, 1), "YZ": (2, 1, 0)}
STRAIN = (2e-5, -1e-5, 3e-5)
FACTORS = {"Service": 1., "Reverse": -2., "Zero": 0.}


def quiet_solve(project):
    with contextlib.redirect_stdout(io.StringIO()):
        return analyze(project)


def membrane_patch(size=20., plane="XY", strain=STRAIN, nu=.2):
    p = SpatialProject(combinations={name: {"Case 1": factor} for name, factor in FACTORS.items()})
    u, v, normal = AXES[plane]
    origin = np.array((19., -7., 41.))
    mesh = MeshDefinition(name="Patch", plane=plane, origin=origin.tolist(),
        parameters={"width": 120., "height": 80.}, mesh_size=size, thickness=.8,
        material=Material("Membrane", E=3600., nu=nu, rho=0.))
    p.surfaces["Patch"] = mesh
    p.surface_analysis_enabled = True
    # Only boundary load/support joints belong to the project; interior nodes
    # are regenerated by the production assembler on each refinement.
    for xyz in surface_geometry(mesh)[2]:
        xy = (np.asarray(xyz)-origin)[[u, v]]
        if xy[0] in (0., 120.) or xy[1] in (0., 80.):
            p.node_at(*xyz)
    corner = p.node_at(*origin)
    base = origin.copy()
    base[normal] -= 40.
    base_name = p.node_at(*base)
    p.nodes[base_name].support = "fixed"
    p.members["Anchor"] = SpatialMember("Anchor", base_name, corner)
    # The off-plane anchor is at the zero-displacement corner and carries no
    # membrane load. Three scalar in-plane restraints remove only rigid modes.
    p.nodes[corner].support = "custom"
    for axis in (u, v):
        setattr(p.nodes[corner], RESTRAINT_FIELDS[axis], True)
    opposite = origin.copy()
    opposite[u] += 120.
    name = p.node_at(*opposite)
    p.nodes[name].support = "custom"
    setattr(p.nodes[name], RESTRAINT_FIELDS[v], True)
    p.surface_supports = {"Patch": {edge: [DOFS[normal]] for edge in ("left", "right", "bottom", "top")}}
    sx, sy, tau = membrane_stress(mesh.material.E, nu, strain)
    for axis, length, other, traction in ((u, 120., v, (sx, tau)), (v, 80., u, (tau, sy))):
        for side in (0., length):
            names = sorted((name for name, node in p.nodes.items()
                if abs(node.coords[axis]-origin[axis]-side) < 1e-9
                and abs(node.coords[normal]-origin[normal]) < 1e-9), key=lambda name: p.nodes[name].coords[other])
            for left, right in zip(names, names[1:]):
                span = p.nodes[right].coords[other]-p.nodes[left].coords[other]
                force = np.asarray(traction)*mesh.thickness*span/2*(-1 if side == 0 else 1)
                for name in (left, right):
                    for direction, magnitude in zip((u, v), force):
                        key = f"L{len(p.loads)}"
                        p.loads[key] = SpatialLoad(key, name, "F"+"XYZ"[direction], float(magnitude))
    p.validate()
    return p


def membrane_metrics(project, result, strain=STRAIN):
    mesh = project.surfaces["Patch"]
    u, v, normal = AXES[mesh.plane]
    mapping = result.solver._pynitegui_surfaces["Patch"]
    points = np.array([(result.solver.nodes[name].X, result.solver.nodes[name].Y,
                        result.solver.nodes[name].Z) for name in mapping["nodes"]])
    xy = (points-np.array(mesh.origin))[:, [u, v]]
    displacement = np.array([result.displacements[name] for name in mapping["nodes"]])
    factor = project.combinations[result.combination]["Case 1"]
    expected_w = membrane_displacement(xy, strain)*factor
    expected_s = membrane_stress(mesh.material.E, mesh.material.nu, strain)*factor
    rows = centre_results(result, "Patch")
    stress = np.array([[row[key] for key in ("Sx", "Sy", "Txy")] for row in rows])
    # Absolute errors also cover the zero combination without a zero denominator.
    return dict(elements=len(rows), max_displacement_error_in=float(abs(displacement[:, [u, v]]-expected_w).max()),
        max_stress_error_ksi=float(abs(stress-expected_s).max()),
        max_normal_displacement_in=float(abs(displacement[:, normal]).max()),
        max_drilling_rotation_rad=float(abs(displacement[:, 3+normal]).max()),
        equilibrium_passed=check_equilibrium(project, result).passed)


def beam_strip(size=30., stiffness_ratio=1., origin=(0., 0., 0.)):
    p = SpatialProject(load_cases=["Pressure", "Beam"], default_load_case="Pressure",
        combinations={"Pressure": {"Pressure": 1.}, "Beam": {"Beam": 1.}, "Reverse": {"Pressure": -2.}})
    # Matched nu=0, isotropic material; beam and shell centrelines coincide.
    p.materials = {p.default_material: Material(p.default_material, E=3600., nu=0., rho=0.)}
    p.sections = {p.default_section: Section(p.default_section, A=1.2, Iy=.216*stiffness_ratio,
                                           Iz=.216*stiffness_ratio, J=.4)}
    for x in (0., 240.):
        name = p.node_at(origin[0]+x, origin[1], origin[2]+6.)
        node = p.nodes[name]
        node.support = "custom"
        node.restraint_x, node.restraint_y, node.restraint_z = x == 0., True, True
    a, b = list(p.nodes)
    p.members["Beam"] = SpatialMember("Beam", a, b)
    p.surfaces["Strip"] = MeshDefinition(name="Strip", plane="XZ", origin=list(origin),
        parameters={"width": 240., "height": 12.}, mesh_size=size, thickness=.6, y_control=[6.],
        material=Material("Slab", E=3600., nu=0., rho=0.))
    p.surface_analysis_enabled = True
    p.surface_supports = {"Strip": {"left": ["DY"], "right": ["DY"]}}
    p.surface_pressures = {"Strip": {"Pressure": 1e-7}}
    p.loads["Line"] = SpatialLoad("Line", "Beam", "FY", -12e-7, position=0., kind="distributed",
                                 end_magnitude=-12e-7, case="Beam")
    p.validate()
    return p


def strip_metrics(project, result):
    mesh = project.surfaces["Strip"]
    material = project.materials[project.default_material]
    section = project.sections[project.default_section]
    length, width = mesh.parameters["width"], mesh.parameters["height"]
    beam_EI = material.E*section.Iz
    slab_EI = mesh.material.E*width*mesh.thickness**3/12
    factors = project.combinations[result.combination]
    line_load = 12e-7*(factors.get("Pressure", 0.)+factors.get("Beam", 0.))
    beam = result.solver.members["Beam"]
    reference_w, reference_beam_m, _ = strip_solution(length/2, length, line_load, beam_EI, slab_EI)
    actual_w = -beam.deflection("dy", length/2, result.combination)
    actual_m = -beam.moment("Mz", length/2, result.combination)
    rows = centre_results(result, "Strip")
    x = np.array([row["position"][0]-mesh.origin[0] for row in rows])
    _, _, reference_slab_m = strip_solution(x, length, line_load, beam_EI, slab_EI)
    actual_slab_m = np.array([row["Mx"]*width for row in rows])
    reference_peak = abs(float(reference_w))
    # Check the entire generated-node displacement field, not just the beam.
    mapping = result.solver._pynitegui_surfaces["Strip"]
    nodes = [result.solver.nodes[name] for name in mapping["nodes"]]
    nodal_x = np.array([node.X-mesh.origin[0] for node in nodes])
    expected, _, _ = strip_solution(nodal_x, length, line_load, beam_EI, slab_EI)
    actual = -np.array([node.DY[result.combination] for node in nodes])
    return dict(elements=len(rows), beam_segments=len(beam.sub_members),
        stiffness_ratio=beam_EI/slab_EI, reference_peak_in=float(reference_w), peak_in=float(actual_w),
        peak_relative_error=float(abs(actual_w/reference_w-1)),
        field_error_relative_to_peak=float(abs(actual-expected).max()/reference_peak),
        beam_moment_relative_error=float(abs(actual_m/reference_beam_m-1)),
        slab_moment_relative_l2=float(np.linalg.norm(actual_slab_m-reference_slab_m)/np.linalg.norm(reference_slab_m)),
        equilibrium_passed=check_equilibrium(project, result).passed)


def drilling_project(size):
    from pynitegui.qt.spatial_examples import example_project
    p = example_project("3d_space_frame")
    p.loads.clear()
    p.surfaces["Floor"] = MeshDefinition(name="Floor", plane="XZ", origin=[0., 144., 0.],
        parameters={"width": 240., "height": 180.}, mesh_size=size, thickness=6.)
    p.surface_pressures = {"Floor": {"Gravity": .001}}
    p.surface_analysis_enabled = True
    p.loads["WindLoad"] = SpatialLoad("WindLoad", "N2", "FZ", 1.5, case="Wind")
    p.validate()
    return p


def drilling_metrics(project):
    """Raw engine solve for diagnosis only, plus the actual application rejection.

    This is deliberately separate from analyze(): it does not change, intercept
    or relax the production equilibrium gate. No raw diagnostic result is sent
    to the UI, exported as engineering data or returned to an MCP client.
    """
    model = FEModel3D()
    for mat in project.materials.values():
        model.add_material(mat.name, mat.E, mat.G, mat.nu, mat.rho)
    for section in project.sections.values():
        model.add_section(section.name, section.A, section.Iy, section.Iz, section.J)
    for node in project.nodes.values():
        model.add_node(node.name, *node.coords)
        model.def_support(node.name, **dict(zip(("support_"+dof for dof in DOFS), node.restraints)))
    for member in project.members.values():
        model.add_member(member.name, member.start, member.end, member.material, member.section, rotation=member.roll)
    attach_surfaces(project, model)
    for load in project.loads.values():
        model.add_node_load(load.target, load.direction, load.magnitude, load.case)
    for name, factors in project.combinations.items():
        model.add_load_combo(name, dict(factors))
    with contextlib.redirect_stdout(io.StringIO()):
        model.analyze_linear()
    raw = AnalysisResult.from_solver(model, "Wind", spatial=True)
    raw.model_signature = model_signature(project)
    check = check_equilibrium(project, raw)
    # A local shell-normal moment is a weak diagonal rotational spring. Its
    # summed global torque should account for the missing external moment.
    torque = sum((quad.T()[:3, :3][2]*float(quad.f("Wind")[5::6].sum())
                  for quad in model.quads.values()), start=np.zeros(3))
    try:
        quiet_solve(project)
    except ValueError as error:
        rejection = str(error)
    else:
        rejection = ""
    return dict(elements=len(model.quads),
        residuals={row.component: float(row.residual) for row in check.rows},
        limits={row.component: float(row.tolerance) for row in check.rows},
        raw_equilibrium_passed=check.passed, summed_drilling_torque_kip_in=torque.tolist(),
        production_rejected="Coupled surface equilibrium failed for Wind" in rejection,
        rejection=rejection)
